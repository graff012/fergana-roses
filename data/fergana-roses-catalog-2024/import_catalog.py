#!/usr/bin/env python3
"""Validate the workbook; upload through Fergana Roses' existing API on --apply."""
import argparse
from collections import Counter
from decimal import Decimal, InvalidOperation
import getpass
import json
import mimetypes
import os
from pathlib import Path
import sys
import urllib.error
import urllib.parse
import urllib.request
import uuid

from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parent


def sheet_rows(sheet):
    values = iter(sheet.values)
    headers = next(values)
    return [dict(zip(headers, row)) for row in values if any(v is not None for v in row)]


def string(value):
    return '' if value is None else str(value).strip()


def validate(workbook, only=None):
    wb = load_workbook(workbook, data_only=True)
    rows = sheet_rows(wb['Flowers'])
    categories = {string(r['categoryName']): r for r in sheet_rows(wb['Categories'])}
    if only:
        rows = [r for r in rows if str(r['catalogNumber']) in only]
        if {str(r['catalogNumber']) for r in rows} != only:
            raise ValueError('One or more requested catalog numbers are absent.')
    errors = []
    if not rows:
        errors.append('No flower rows selected.')
    seen = set()
    for row in rows:
        n = row['catalogNumber']
        prefix = f"#{n} {row['name']}"
        if n in seen:
            errors.append(f'{prefix}: duplicate catalog number')
        seen.add(n)
        name = string(row['name'])
        if not name or len(name) > 250:
            errors.append(f'{prefix}: name must contain 1–250 characters')
        for key in ('smell', 'flowerSize', 'height'):
            if len(string(row[key])) > 250:
                errors.append(f'{prefix}: {key} exceeds 250 characters')
        try:
            price = Decimal(string(row['price']))
            if not price.is_finite() or price <= 0:
                raise ValueError()
        except (InvalidOperation, ValueError):
            errors.append(f'{prefix}: enter a positive price in UZS')
        try:
            stock = Decimal(string(row['stock']))
            if not stock.is_finite() or stock < 0 or stock != stock.to_integral_value():
                raise ValueError()
        except (InvalidOperation, ValueError):
            errors.append(f'{prefix}: enter a nonnegative integer stock (0 is allowed)')
        cat = string(row['categoryName'])
        if not cat or cat not in categories:
            errors.append(f'{prefix}: choose a categoryName listed on Categories')
        if string(row['reviewNotes']):
            errors.append(f'{prefix}: resolve reviewNotes and clear that cell')
        image = (workbook.parent / string(row['image'])).resolve()
        if not image.is_relative_to(workbook.parent.resolve()) or not image.is_file():
            errors.append(f'{prefix}: image is missing or outside the package')
        elif image.stat().st_size > 10 * 1024 * 1024:
            errors.append(f'{prefix}: image exceeds API 10 MB limit')
    return rows, categories, errors


def request(api, path, token, data=None, content_type=None):
    headers = {'Authorization': f'Bearer {token}', 'Accept': 'application/json'}
    if isinstance(data, dict):
        data = json.dumps(data).encode()
        content_type = 'application/json'
    if content_type:
        headers['Content-Type'] = content_type
    req = urllib.request.Request(api + path, data=data, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=90) as response:
            return json.load(response)
    except urllib.error.HTTPError as exc:
        # Do not retry POST automatically: the server may already have saved it.
        raise RuntimeError(f'{path}: HTTP {exc.code}: {exc.read().decode()[:400]}') from exc


def multipart(row, category_id, workbook):
    boundary = 'fergana-' + uuid.uuid4().hex
    parts = []
    for key in ('name', 'smell', 'flowerSize', 'height', 'price', 'stock', 'categoryId'):
        value = category_id if key == 'categoryId' else string(row[key])
        if key == 'stock':
            value = str(int(Decimal(value)))
        parts.append((f'--{boundary}\r\nContent-Disposition: form-data; name="{key}"\r\n\r\n{value}\r\n').encode())
    path = workbook.parent / row['image']
    mime = mimetypes.guess_type(path.name)[0] or 'image/jpeg'
    # ASCII filenames are generated by the extractor.
    parts.append((f'--{boundary}\r\nContent-Disposition: form-data; name="image"; filename="{path.name}"\r\nContent-Type: {mime}\r\n\r\n').encode())
    parts.extend([path.read_bytes(), f'\r\n--{boundary}--\r\n'.encode()])
    return b''.join(parts), f'multipart/form-data; boundary={boundary}'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--workbook', type=Path, default=ROOT / 'fergana_roses_2024.xlsx')
    parser.add_argument('--only', help='Comma-separated catalog numbers to validate/import')
    parser.add_argument('--apply', action='store_true', help='Actually upload; default is offline validation')
    parser.add_argument('--api-url', help='Explicit API root, ending in /api (required with --apply)')
    parser.add_argument('--create-categories', action='store_true', help='Create missing named categories when applying')
    args = parser.parse_args()
    workbook = args.workbook.resolve()
    only = {s.strip() for s in args.only.split(',')} if args.only else None
    rows, categories, errors = validate(workbook, only)
    print(f'{len(rows)} selected flowers; categories: {dict(Counter(string(r["categoryName"]) for r in rows))}')
    if errors:
        print(f'{len(errors)} unresolved items. First 20:')
        print('\n'.join(errors[:20]))
        return 2
    print('Workbook validation passed; every selected image exists.')
    if not args.apply:
        print('Validation only. No network requests or uploads made.')
        return 0
    if not args.api_url:
        raise ValueError('--api-url is required with --apply')
    api = args.api_url.rstrip('/')
    parsed = urllib.parse.urlparse(api)
    if parsed.scheme != 'https' and not (parsed.scheme == 'http' and parsed.hostname in ('localhost', '127.0.0.1')):
        raise ValueError('Use HTTPS, or HTTP on localhost.')
    token = os.environ.get('FERGANA_ADMIN_TOKEN') or getpass.getpass('Admin bearer token: ')
    if not token.strip():
        raise ValueError('Admin token is required')
    # Refuse ambiguous existing names and duplicate flowers before any writes.
    remote = request(api, '/categories', token)
    remote_categories = remote if isinstance(remote, list) else remote['categories']
    by_name = {}
    ids = {c['id'] for c in remote_categories}
    for cat in remote_categories:
        key = cat['name'].strip().casefold()
        if key in by_name:
            raise ValueError(f'Ambiguous remote category: {cat["name"]}')
        by_name[key] = cat['id']
    flowers = request(api, '/flowers', token)
    flowers = flowers if isinstance(flowers, list) else flowers['flowers']
    existing = {f['name'].strip().casefold() for f in flowers}
    duplicates = [r['name'] for r in rows if string(r['name']).casefold() in existing]
    if duplicates:
        raise ValueError(f'Flowers already exist; use --only to exclude them: {duplicates}')
    resolved = {}
    missing = []
    for name in sorted({string(r['categoryName']) for r in rows}):
        explicit_ids = {string(r['categoryId']) for r in rows if string(r['categoryName']) == name and string(r['categoryId'])}
        mapped = string(categories[name].get('categoryId'))
        if mapped:
            explicit_ids.add(mapped)
        if len(explicit_ids) > 1:
            raise ValueError(f'Conflicting category IDs for {name}')
        explicit = next(iter(explicit_ids), '')
        if explicit:
            if explicit not in ids:
                raise ValueError(f'{name}: category ID {explicit} is absent on this server; update workbook mapping')
            resolved[name] = explicit
        elif name.casefold() in by_name:
            resolved[name] = by_name[name.casefold()]
        else:
            missing.append(name)
    if missing and not args.create_categories:
        raise ValueError(f'Missing categories: {missing}. Create/map them first, or use --create-categories.')
    for name in missing:
        result = request(api, '/categories/create', token, {'name': name})
        resolved[name] = result['category']['id']
        print(f'Created category: {name}')
    log = workbook.parent / 'import_results.jsonl'
    # Stop on first error. Successful rows are logged immediately for recovery.
    for row in rows:
        payload, content_type = multipart(row, resolved[string(row['categoryName'])], workbook)
        result = request(api, '/flowers/create', token, payload, content_type)
        saved = result['flower']
        with log.open('a', encoding='utf-8') as stream:
            stream.write(json.dumps({'api': api, 'catalogNumber': row['catalogNumber'], 'name': row['name'], 'id': saved['id']}, ensure_ascii=False) + '\n')
        print(f'Imported #{row["catalogNumber"]}: {row["name"]}')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, RuntimeError, OSError, KeyError) as exc:
        print(f'Import stopped: {exc}', file=sys.stderr)
        sys.exit(1)
